import 'server-only'
import { createServerClient } from '@supabase/ssr'
import { createAdminClient } from '@/lib/supabase/admin'
import { checkRateLimit } from '@/lib/security/rate-limit'
import {
  LIMITS, classifyFailure, digestCorrelationId, fingerprintOf, isNoise, isReferenceId, moduleFromPath, newReferenceId, severityFor,
  type IngestPayload, type LogCategory, type LogSource,
} from './contract'
import { describeUserAgent, sanitizeDetails, sanitizeLabel, sanitizePath, sanitizeStack, sanitizeText } from './sanitize'
import { appBuild, resolveRuntimeEnvironment } from './environment'

/**
 * Server / API / worker side of the System Logs contract.
 *
 * Guarantees (each is tested in server.test.ts):
 *   - never throws and never changes the caller's outcome: a logging failure is swallowed (one console line);
 *   - bounded: per-fingerprint and process-wide rate limits, a short database timeout, and a 5-minute back-off when
 *     the storage is not installed (migration pending) — normal requests are never slowed by a missing table;
 *   - sanitized before storage; actor and organization only from trusted server data;
 *   - existing console logging at call sites is kept (this does not replace console.error).
 */

/**
 * Server reference header. Route handlers that report a failure return it (and `referenceId` in the JSON body) so the
 * browser's report of the same failure links to the server's. Generated by the server; an incoming value is ignored.
 */
export const REQUEST_ID_HEADER = 'x-request-id'

const STORAGE_MISSING = new Set(['PGRST202', '42883', 'PGRST205', '42P01'])
const STORE_TIMEOUT_MS = 3_000
const PER_FINGERPRINT_PER_MINUTE = 30
const PROCESS_PER_MINUTE = 300

type ReporterState = { unavailableUntil: number; lastWarnAt: number }
const STATE_KEY = Symbol.for('serapod2u.system-logs.reporter')
const state = (): ReporterState => {
  const holder = globalThis as any
  holder[STATE_KEY] ??= { unavailableUntil: 0, lastWarnAt: 0 }
  return holder[STATE_KEY]
}

/** Exported for tests only. */
export function __resetReporterForTests() {
  delete (globalThis as any)[STATE_KEY]
}

export interface ServerReportInput {
  error?: unknown
  /** Overrides the error's own message (already human-written; still sanitized). */
  message?: string
  category?: LogCategory
  status?: number | null
  code?: string | null
  module?: string | null
  action?: string | null
  apiRoute?: string | null
  method?: string | null
  pagePath?: string | null
  source?: Extract<LogSource, 'server' | 'worker'>
  /** Trusted: from the verified session or server-loaded rows. Never from a request body. */
  actorId?: string | null
  organizationId?: string | null
  /** Reference to use (a fresh REQ-/JOB- id when absent). Never taken from a client-supplied header. */
  referenceId?: string | null
  /** Scheduler/worker: the X-Request-ID returned by the route it called (links to that route's own report). */
  serverReferenceId?: string | null
  correlationId?: string | null
  details?: Record<string, unknown>
  userAgent?: string | null
}

function warnOnce(message: string, extra?: Record<string, unknown>) {
  const s = state()
  if (Date.now() - s.lastWarnAt < 60_000) return
  s.lastWarnAt = Date.now()
  console.warn(`[system-logs] ${message}`, extra ?? '')
}

function errorFacts(error: unknown) {
  const e = (error ?? {}) as any
  return {
    name: typeof e?.name === 'string' ? e.name : undefined,
    message: typeof e === 'string' ? e : typeof e?.message === 'string' ? e.message : undefined,
    code: typeof e?.code === 'string' || typeof e?.code === 'number' ? String(e.code) : undefined,
    status: typeof e?.status === 'number' ? e.status : typeof e?.statusCode === 'number' ? e.statusCode : undefined,
    stack: typeof e?.stack === 'string' ? e.stack : undefined,
    digest: typeof e?.digest === 'string' ? e.digest : undefined,
    details: typeof e?.details === 'string' ? e.details : undefined,
    hint: typeof e?.hint === 'string' ? e.hint : undefined,
  }
}

/** Builds the stored payload (pure; exported for tests). */
export function buildServerPayload(input: ServerReportInput): IngestPayload | null {
  const f = errorFacts(input.error)
  const rawMessage = input.message ?? f.message ?? (input.status ? `HTTP ${input.status}` : 'Unknown server error')
  if (isNoise(rawMessage, f.stack) || isNoise(f.digest)) return null
  const status = input.status ?? f.status ?? null
  const category = input.category ?? classifyFailure({ status, name: f.name, message: rawMessage, code: input.code ?? f.code })
  if (category === 'cancelled') return null
  const source = input.source ?? 'server'
  const message = sanitizeText(rawMessage) || 'Unknown server error'
  const code = sanitizeLabel(input.code ?? f.code, LIMITS.code)
  const module = sanitizeLabel(input.module, LIMITS.module)
  const action = sanitizeLabel(input.action, LIMITS.action)
  const apiRoute = input.apiRoute ? sanitizePath(input.apiRoute) : null
  const stack = f.stack ? sanitizeStack(f.stack) : null
  const details = sanitizeDetails({
    ...(f.details ? { db_details: f.details } : {}),
    ...(f.hint ? { db_hint: f.hint } : {}),
    ...(input.details ?? {}),
  })
  const referenceId = isReferenceId(input.referenceId) ? input.referenceId : newReferenceId(source === 'worker' ? 'JOB' : 'REQ')
  const method = typeof input.method === 'string' ? input.method.toUpperCase() : null
  return {
    kind: 'error',
    reference_id: referenceId,
    occurred_at: new Date().toISOString(),
    source,
    environment: resolveRuntimeEnvironment(),
    app_build: appBuild(),
    fingerprint: fingerprintOf({ source, category, code, module, action, route: apiRoute, message, stack }),
    category,
    severity: severityFor(category),
    message,
    actor_id: input.actorId ?? null,
    organization_id: input.organizationId ?? null,
    code,
    module,
    action,
    page_path: input.pagePath ? sanitizePath(input.pagePath) : null,
    api_route: apiRoute,
    http_method: method && ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'].includes(method) ? method : null,
    http_status: typeof status === 'number' && status >= 0 && status <= 599 ? status : null,
    stack,
    correlation_id: isReferenceId(input.correlationId) ? input.correlationId : digestCorrelationId(f.digest),
    server_reference_id: isReferenceId(input.serverReferenceId) ? input.serverReferenceId : null,
    details,
    client: input.userAgent ? describeUserAgent(input.userAgent) : {},
  }
}

/** Stores a sanitized payload. Never throws. Returns true when the database accepted it. */
export async function storeDiagnostic(payload: IngestPayload, client?: { rpc: (...args: any[]) => PromiseLike<any> }): Promise<{ stored: boolean; reason?: string; result?: any }> {
  const s = state()
  if (Date.now() < s.unavailableUntil) return { stored: false, reason: 'storage_unavailable' }
  if (!checkRateLimit(`system-logs:process`, PROCESS_PER_MINUTE, 60_000).allowed
      || !checkRateLimit(`system-logs:fp:${payload.fingerprint}:${payload.organization_id ?? '-'}`, PER_FINGERPRINT_PER_MINUTE, 60_000).allowed) {
    return { stored: false, reason: 'rate_limited' }
  }
  try {
    const admin = client ?? (createAdminClient(STORE_TIMEOUT_MS) as any)
    const { data, error } = await admin.rpc('system_log_ingest', { p: payload })
    if (error) {
      if (STORAGE_MISSING.has(error.code)) {
        s.unavailableUntil = Date.now() + 5 * 60_000
        warnOnce('storage not installed (apply 20261017100000_system_logs_foundation.sql); diagnostics are not being stored')
        return { stored: false, reason: 'storage_unavailable' }
      }
      warnOnce('ingest refused', { code: error.code })
      return { stored: false, reason: error.code || 'ingest_failed' }
    }
    return { stored: data?.stored !== false, result: data }
  } catch (err) {
    warnOnce('ingest failed', { name: (err as any)?.name })
    return { stored: false, reason: 'ingest_failed' }
  }
}

async function organizationOf(actorId: string): Promise<string | null> {
  try {
    const admin = createAdminClient(STORE_TIMEOUT_MS) as any
    const { data } = await admin.from('users').select('organization_id').eq('id', actorId).maybeSingle()
    return data?.organization_id ?? null
  } catch {
    return null
  }
}

/**
 * Report a server/API/worker failure. Returns the reference id to show the user (or null for non-diagnostic
 * outcomes such as cancellations). Safe to call without awaiting; never throws.
 */
export async function reportServerError(input: ServerReportInput): Promise<string | null> {
  try {
    const payload = buildServerPayload(input)
    if (!payload) return null
    if (payload.actor_id && !payload.organization_id) payload.organization_id = await organizationOf(payload.actor_id)
    await storeDiagnostic(payload)
    return payload.reference_id
  } catch {
    return null
  }
}

/** Background job failure through the existing worker infrastructure (no user; organization unknown unless given). */
export function reportWorkerFailure(worker: string, input: Omit<ServerReportInput, 'source' | 'module' | 'action'> & { action?: string }) {
  return reportServerError({ ...input, source: 'worker', module: 'Background jobs', action: input.action ?? worker, details: { worker, ...(input.details ?? {}) } })
}

/** Response header carrying the server reference of a failed request (read by the browser reporter to link reports). */
export function referenceHeaders(referenceId: string | null | undefined): Record<string, string> {
  return referenceId ? { [REQUEST_ID_HEADER]: referenceId } : {}
}

/** Signed-in user (id) from a raw Cookie header, for onRequestError where no Next request object exists. */
async function actorFromCookieHeader(cookieHeader: string | undefined): Promise<string | null> {
  if (!cookieHeader || !/sb-[^=]*-auth-token/.test(cookieHeader)) return null
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
  if (!url || !key) return null
  const jar = new Map<string, string>()
  for (const part of cookieHeader.split(';')) {
    const i = part.indexOf('=')
    if (i > 0) jar.set(part.slice(0, i).trim(), decodeURIComponent(part.slice(i + 1).trim()))
  }
  try {
    const supabase = createServerClient(url, key, { cookies: { get: (n: string) => jar.get(n), set() {}, remove() {} } })
    const { data } = await supabase.auth.getUser()
    return data.user?.id ?? null
  } catch {
    return null
  }
}

/** Next.js instrumentation onRequestError: uncaught render / route handler / server action failures. */
export async function reportRequestError(
  error: unknown,
  request: { path?: string; method?: string; headers?: Record<string, string | string[] | undefined> },
  context: { routerKind?: string; routePath?: string; routeType?: string; renderSource?: string } = {},
): Promise<void> {
  try {
    const f = errorFacts(error)
    if (isNoise(f.message, f.stack) || isNoise(f.digest)) return
    const headers = request.headers ?? {}
    const cookie = Array.isArray(headers.cookie) ? headers.cookie.join('; ') : headers.cookie
    const isRoute = context.routeType === 'route'
    const actorId = await actorFromCookieHeader(cookie)
    await reportServerError({
      error,
      status: 500,
      category: f.status ? undefined : 'unexpected',
      module: moduleFromPath(context.routePath ?? request.path ?? ''),
      action: `${context.routeType ?? 'request'} ${context.routePath ?? ''}`.trim(),
      apiRoute: isRoute ? request.path : null,
      pagePath: isRoute ? null : request.path,
      method: request.method,
      actorId,
      details: { route_path: context.routePath, route_type: context.routeType, router: context.routerKind, render_source: context.renderSource, uncaught: true },
      userAgent: Array.isArray(headers['user-agent']) ? headers['user-agent'][0] : headers['user-agent'],
    })
  } catch {
    // Never let diagnostics interfere with Next.js error handling.
  }
}
