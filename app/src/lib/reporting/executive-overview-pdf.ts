/**
 * Serapod Executive Overview Report — branded A4 landscape PDF.
 *
 * Built only from the `ExecutiveOverviewReport` DTO that renders the Overview
 * tab, so the two cannot disagree: no data access and no second KPI
 * calculation here, only formatting. Visual language: `report-pdf-kit.ts`,
 * shared with the Product Performance report.
 */

import { formatReportDate } from './product-analytics'
import { executiveOverviewFilename, type ExecutiveOverviewReport } from './executive-overview'
import {
  createReportPdf,
  formatChange,
  formatCount,
  formatDateTimeMyt,
  formatRM,
  type ReportPdfFile,
} from './report-pdf-kit'

export const EXECUTIVE_OVERVIEW_PDF_TITLE = 'SERAPOD EXECUTIVE OVERVIEW REPORT'

const STATUS_LABEL: Record<string, string> = {
  approved: 'Approved',
  warehouse_packed: 'Warehouse packed',
  shipped_distributor: 'Shipped',
  closed: 'Closed',
}

const BUYER_TYPE_LABEL: Record<string, string> = { DIST: 'Distributor', SHOP: 'Shop' }

export async function buildExecutiveOverviewPdf(
  report: ExecutiveOverviewReport,
  options: { generatedAt?: string | null; generatedBy?: string | null } = {},
): Promise<ReportPdfFile> {
  const { period, summary, comparison } = report
  const generatedAt = options.generatedAt ?? new Date().toISOString()
  const mtd = period.isCurrentMonth ? ' (month to date)' : ''
  const versus = `${period.rangeLabel} vs ${period.comparisonRangeLabel}`

  const pdf = await createReportPdf({
    title: EXECUTIVE_OVERVIEW_PDF_TITLE,
    scope: `${period.label}${period.isCurrentMonth ? ' · Month to date' : ''}`,
    runningScope: `${period.label} · ${period.rangeLabel}`,
  })

  // ══ PAGE 1 — SUMMARY ═══════════════════════════════════════════════════
  pdf.infoGrid([
    ['REPORTING MONTH', period.label],
    ['REPORT PERIOD', period.rangeLabel + mtd],
    ['COMPARISON PERIOD', period.comparisonRangeLabel + (period.isCurrentMonth ? ' (same elapsed days)' : '')],
    ['GENERATED', formatDateTimeMyt(generatedAt)],
    ['GENERATED BY', options.generatedBy || '—'],
    ['REPORTING TIMEZONE', period.timeZone],
    ['SALES ORDER TYPES', 'D2H (distributor sales) + S2D (shop sales)'],
    ['APPROVED STATUSES', report.meta.approvedStatuses.join(', ')],
    ['REPORT DATE FIELD', report.meta.dateField],
    ['ORDER VALUE', report.meta.valueField],
  ])
  if (report.meta.notice) pdf.note(`Data notice: ${report.meta.notice}`)
  if (report.isEmpty) pdf.emptyNote(`No orders were recorded in ${period.label} (${period.rangeLabel}). All figures below are zero.`)

  pdf.sectionBand('MONTHLY SALES SUMMARY', versus)
  pdf.kpiRow([
    {
      label: 'Approved Sales Value',
      value: formatRM(summary.approvedSalesValue),
      note: `${formatChange(comparison.approvedSalesValue)} vs comparison (${formatRM(comparison.approvedSalesValue.previous)})`,
      delta: comparison.approvedSalesValue.changePct,
    },
    {
      label: 'Confirmed Sales Orders',
      value: formatCount(summary.approvedSalesOrders),
      note: `${formatChange(comparison.approvedSalesOrders)} vs comparison (${formatCount(comparison.approvedSalesOrders.previous)})`,
      delta: comparison.approvedSalesOrders.changePct,
    },
    {
      label: 'Total Units Sold',
      value: formatCount(summary.unitsSold),
      note: `${formatChange(comparison.unitsSold)} vs comparison (${formatCount(comparison.unitsSold.previous)})`,
      delta: comparison.unitsSold.changePct,
    },
    {
      label: 'Active Buyers',
      value: formatCount(summary.activeBuyers),
      note: `${formatCount(summary.activeDistributorBuyers)} distributors · ${formatCount(summary.activeShopBuyers)} shops`,
    },
    {
      label: 'Avg Order Value',
      value: summary.avgOrderValue === null ? '—' : formatRM(summary.avgOrderValue),
      note: 'approved sales value ÷ confirmed orders',
    },
  ])

  pdf.sectionBand('SALES BY CHANNEL, PIPELINE & PURCHASES', period.rangeLabel + mtd)
  pdf.kpiRow([
    {
      label: 'Distributor Sales (D2H)',
      value: formatRM(summary.distributorSalesValue),
      note: `${formatCount(summary.distributorSalesOrders)} orders · ${formatChange(comparison.distributorSalesValue)} vs comparison`,
      delta: comparison.distributorSalesValue.changePct,
    },
    {
      label: 'Shop Sales (S2D)',
      value: formatRM(summary.shopSalesValue),
      note: `${formatCount(summary.shopSalesOrders)} orders · ${formatChange(comparison.shopSalesValue)} vs comparison`,
      delta: comparison.shopSalesValue.changePct,
    },
    {
      label: 'Sales Pipeline',
      value: formatRM(summary.pipelineValue),
      note: `${formatCount(summary.pipelineOrders)} submitted, awaiting approval — not sales`,
    },
    {
      label: 'Cancelled Orders',
      value: formatCount(summary.cancelledOrders),
      note: `${formatRM(summary.cancelledValue)} — excluded from sales`,
    },
    {
      label: 'H2M Manufacturer Purchases',
      value: formatRM(summary.purchaseValue),
      note: `${formatCount(summary.purchaseOrders)} approved purchase orders — never sales`,
    },
  ])

  pdf.sectionBand('THIS PERIOD VS PREVIOUS PERIOD', versus, pdf.tableHeight(6))
  pdf.table({
    head: ['Metric', 'Current', 'Previous', 'Change'],
    body: [
      ['Approved Sales Value', formatRM(comparison.approvedSalesValue.current), formatRM(comparison.approvedSalesValue.previous), formatChange(comparison.approvedSalesValue)],
      ['Distributor Sales (D2H)', formatRM(comparison.distributorSalesValue.current), formatRM(comparison.distributorSalesValue.previous), formatChange(comparison.distributorSalesValue)],
      ['Shop Sales (S2D)', formatRM(comparison.shopSalesValue.current), formatRM(comparison.shopSalesValue.previous), formatChange(comparison.shopSalesValue)],
      ['Confirmed Sales Orders', formatCount(comparison.approvedSalesOrders.current), formatCount(comparison.approvedSalesOrders.previous), formatChange(comparison.approvedSalesOrders)],
      ['Total Units Sold', formatCount(comparison.unitsSold.current), formatCount(comparison.unitsSold.previous), formatChange(comparison.unitsSold)],
      ['Active Buyers', formatCount(comparison.activeBuyers.current), formatCount(comparison.activeBuyers.previous), formatChange(comparison.activeBuyers)],
    ],
    widths: [0.34, 0.22, 0.22, 0.22],
    align: ['left', 'right', 'right', 'right'],
    boldFirst: true,
  })
  if (summary.unclassifiedOrders > 0) {
    pdf.note(`${formatCount(summary.unclassifiedOrders)} order(s) worth ${formatRM(summary.unclassifiedValue)} have no recognised order type and are excluded from sales.`)
  }

  // ── Trends ─────────────────────────────────────────────────────────────
  pdf.sectionBand('DAILY APPROVED SALES TREND', period.rangeLabel + mtd, 72)
  if (report.dailyTrend.length === 0) {
    pdf.emptyNote('No days in the selected report period.')
  } else {
    const peakValue = Math.max(...report.dailyTrend.map((row) => row.value), 0)
    const peakUnits = Math.max(...report.dailyTrend.map((row) => row.units), 0)
    pdf.barChart({
      bars: report.dailyTrend.map((row) => ({ label: row.label, value: row.value })),
      line: report.dailyTrend.map((row) => row.units),
      caption: `Bars: approved sales value by SO date (peak ${formatRM(peakValue)})   ·   Line: units sold (peak ${formatCount(peakUnits)})`,
    })
  }

  pdf.sectionBand('MONTHLY SALES TREND', `Approved sales, last ${report.monthlyTrend.length} months to ${formatReportDate(period.endDate)}`, 62)
  pdf.barChart({
    bars: report.monthlyTrend.map((row) => ({ label: `${row.label}${row.isPartial ? ' (MTD)' : ''}`, value: row.value })),
    caption: 'Bars: approved sales value per calendar month (D2H + S2D)',
    height: 34,
  })
  pdf.table({
    head: ['Month', 'Approved Sales Value', 'Confirmed Orders', 'Units Sold'],
    body: report.monthlyTrend.map((row) => [
      `${row.label}${row.isPartial ? ' (month to date)' : ''}`,
      formatRM(row.value),
      formatCount(row.orders),
      formatCount(row.units),
    ]),
    widths: [0.31, 0.25, 0.22, 0.22],
    align: ['left', 'right', 'right', 'right'],
    boldFirst: true,
  })

  // ── Products & buyers ──────────────────────────────────────────────────
  pdf.sectionBand('PRODUCT DISTRIBUTION', 'Top variants by units on approved sales orders', pdf.tableHeight(report.productMix.length || 1))
  if (report.productMix.length === 0) {
    pdf.emptyNote('No products were sold on approved orders in the selected report period.')
  } else {
    pdf.table({
      head: ['#', 'Product / Variant', 'Units Sold', 'Share of Units', 'Sales Value'],
      body: report.productMix.map((row, index) => [
        String(index + 1),
        row.name,
        formatCount(row.units),
        row.unitsSharePct === null ? '—' : `${row.unitsSharePct.toFixed(1)}%`,
        formatRM(row.value),
      ]),
      widths: [0.05, 0.45, 0.15, 0.15, 0.2],
      align: ['center', 'left', 'right', 'right', 'right'],
    })
  }

  pdf.sectionBand('BUYER PERFORMANCE', 'Top distributors and shops by approved sales value', pdf.tableHeight(report.topBuyers.length || 1))
  if (report.topBuyers.length === 0) {
    pdf.emptyNote('No buyers placed approved sales orders in the selected report period.')
  } else {
    pdf.table({
      head: ['#', 'Buyer', 'Type', 'Orders', 'Units', 'Sales Value', 'Share'],
      body: report.topBuyers.map((row, index) => [
        String(index + 1),
        row.name,
        BUYER_TYPE_LABEL[String(row.buyerType)] ?? (row.buyerType || '—'),
        formatCount(row.orders),
        formatCount(row.units),
        formatRM(row.value),
        row.valueSharePct === null ? '—' : `${row.valueSharePct.toFixed(1)}%`,
      ]),
      widths: [0.05, 0.37, 0.11, 0.1, 0.1, 0.17, 0.1],
      align: ['center', 'left', 'left', 'right', 'right', 'right', 'right'],
    })
  }

  pdf.sectionBand('LATEST APPROVED SALES ORDERS', 'Most recent by SO date in the report period', pdf.tableHeight(report.recentOrders.length || 1))
  if (report.recentOrders.length === 0) {
    pdf.emptyNote('No approved sales orders in the selected report period.')
  } else {
    pdf.table({
      head: ['SO Date', 'Order No', 'Buyer', 'Type', 'Status', 'Units', 'Sales Value'],
      body: report.recentOrders.map((row) => [
        formatReportDate(row.orderDate),
        row.orderNo,
        row.buyerName,
        row.orderType,
        STATUS_LABEL[row.status] ?? row.status,
        formatCount(row.units),
        formatRM(row.value),
      ]),
      widths: [0.11, 0.17, 0.3, 0.07, 0.13, 0.08, 0.14],
      align: ['left', 'left', 'left', 'left', 'left', 'right', 'right'],
    })
  }

  pdf.sectionBand('METRIC DEFINITIONS', undefined, 40)
  pdf.note([
    'Approved Sales = D2H (distributor purchases from HQ) and S2D (shop purchases from a distributor) orders in approved, warehouse packed, shipped or closed status, valued as the sum of order lines.',
    'Submitted orders are pipeline, cancelled orders are reported separately, and H2M (HQ purchases from manufacturers) are purchases — none of them are counted as sales.',
    'Units, buyers, product distribution, buyer performance and both trends use the same approved-sales orders as the headline value.',
    'Orders are assigned to a month by their SO date (orders.order_date, Malaysia time), so a backdated order belongs to the month it is dated in.',
    'This differs from Distributor Analytics "Order Value", which covers D2H only in every status (including draft, submitted and cancelled), and from Product Analytics "Order Value", which covers approved, closed and submitted orders of every type including H2M.',
  ].join(' '))

  return pdf.finish(executiveOverviewFilename(period), generatedAt)
}
