/**
 * Shared building blocks for Serapod monthly report PDFs.
 *
 * The visual language is the Product Performance report's
 * (`product-analytics-pdf.ts`), lifted out so new reports share it rather than
 * copy it: A4 landscape, white page, ink headings, Serapod orange accents, the
 * metadata grid, beige section bands, KPI cards, grid tables, drawn (never
 * screenshotted) charts and the "Page n of N" footer.
 *
 * Formatting only — a report generator passes in DTO values; nothing here
 * reads data or computes a metric.
 */

export type Rgb = [number, number, number]

export const PDF_COLORS = {
  INK: [26, 26, 26] as Rgb,
  MUTED: [120, 120, 120] as Rgb,
  ORANGE: [232, 93, 4] as Rgb,
  BAND: [243, 238, 230] as Rgb,
  BAND_BORDER: [226, 219, 205] as Rgb,
  BOX_BORDER: [222, 222, 222] as Rgb,
  BOX_FILL: [249, 250, 251] as Rgb,
  STRIPE: [248, 248, 248] as Rgb,
  POSITIVE: [22, 128, 61] as Rgb,
  NEGATIVE: [185, 28, 28] as Rgb,
}

const { INK, MUTED, ORANGE, BAND, BAND_BORDER, BOX_BORDER, BOX_FILL, STRIPE, POSITIVE, NEGATIVE } = PDF_COLORS

export function formatCount(value: number): string {
  return Math.round(value).toLocaleString('en-MY')
}

export function formatDecimal(value: number, digits = 1): string {
  return value.toLocaleString('en-MY', { minimumFractionDigits: digits, maximumFractionDigits: digits })
}

export function formatRM(value: number): string {
  return `RM ${value.toLocaleString('en-MY', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

/** `null` growth means the comparison window had no baseline — never "0%". */
export function formatGrowth(value: number | null): string {
  if (value === null) return 'new'
  return `${value >= 0 ? '+' : ''}${value.toFixed(1)}%`
}

/** Growth for a current/previous pair: "—" when both are zero, "new" when only the current has a value. */
export function formatChange(comparison: { current: number; previous: number; changePct: number | null }): string {
  if (comparison.changePct === null && !(comparison.current > 0)) return '—'
  return formatGrowth(comparison.changePct)
}

export function formatDateTimeMyt(value: string | null): string {
  if (!value) return '—'
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return '—'
  return date.toLocaleString('en-MY', {
    day: '2-digit', month: 'short', year: 'numeric',
    hour: '2-digit', minute: '2-digit', hour12: false,
    timeZone: 'Asia/Kuala_Lumpur',
  })
}

export interface ReportPdfFile {
  blob: Blob
  filename: string
  size: number
}

export interface KpiCard {
  label: string
  value: string
  note: string
  /** Colours the note: green when ≥ 0, red when < 0, muted when absent. */
  delta?: number | null
}

export interface BarChartInput {
  bars: { label: string; value: number }[]
  /** Optional second series drawn as a line on its own scale. */
  line?: number[]
  caption: string
  height?: number
}

/**
 * Open an A4 landscape report. `title` is the page-1 heading and the running
 * header on later pages; `scope` is the orange right-hand caption on both.
 */
export async function createReportPdf(options: { title: string; scope: string; runningScope?: string }) {
  const [{ default: jsPDF }, autoTableModule] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
  ])
  const autoTable = autoTableModule.default

  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 12
  const contentWidth = pageWidth - margin * 2
  const FOOTER_RESERVE = 14
  const CONTINUE_TOP = 22
  const contentBottom = pageHeight - FOOTER_RESERVE
  /** Tables up to this many rows are kept on one page; ROW_MM is one 7.5pt grid row. */
  const KEEP_TOGETHER_ROWS = 15
  const ROW_MM = 6.8

  let y = 14

  const ensureSpace = (needed: number) => {
    if (y + needed > contentBottom) {
      doc.addPage()
      y = CONTINUE_TOP
    }
  }

  const newPage = () => {
    doc.addPage()
    y = CONTINUE_TOP
  }

  // ── Title block ────────────────────────────────────────────────────────
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.setTextColor(...INK)
  doc.text(options.title, margin, y + 4)
  doc.setFontSize(10)
  doc.setTextColor(...ORANGE)
  doc.text(options.scope, pageWidth - margin, y + 4, { align: 'right' })
  y += 9
  doc.setDrawColor(...BAND_BORDER)
  doc.line(margin, y, pageWidth - margin, y)
  y += 5

  /** Two-column metadata box: reporting month, period, generated by/at, definitions. */
  const infoGrid = (pairs: Array<[string, string]>) => {
    const infoRowH = 6
    const rowsPerCol = Math.ceil(pairs.length / 2)
    const infoH = infoRowH * rowsPerCol + 7
    ensureSpace(infoH + 6)
    doc.setDrawColor(...BOX_BORDER)
    doc.setFillColor(...BOX_FILL)
    doc.roundedRect(margin, y, contentWidth, infoH, 2, 2, 'FD')
    const colGap = contentWidth / 2
    pairs.forEach(([label, value], index) => {
      const col = Math.floor(index / rowsPerCol)
      const row = index % rowsPerCol
      const lx = margin + 4 + col * colGap
      const ly = y + 7 + row * infoRowH
      doc.setFont('helvetica', 'bold')
      doc.setFontSize(6.8)
      doc.setTextColor(...MUTED)
      doc.text(label, lx, ly)
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(8)
      doc.setTextColor(...INK)
      doc.text(doc.splitTextToSize(value, colGap - 50)[0], lx + 46, ly)
    })
    y += infoH + 6
  }

  /** `keepWith` reserves room for the band's first block (table or chart) so a band is never orphaned. */
  const sectionBand = (title: string, note?: string, keepWith = 24) => {
    ensureSpace(keepWith)
    doc.setDrawColor(...BAND_BORDER)
    doc.setFillColor(...BAND)
    doc.rect(margin, y, contentWidth, 8, 'FD')
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(9.5)
    doc.setTextColor(...INK)
    doc.text(title, margin + 3, y + 5.5)
    if (note) {
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(7.5)
      doc.setTextColor(...MUTED)
      doc.text(note, pageWidth - margin - 3, y + 5.5, { align: 'right', maxWidth: contentWidth * 0.6 })
    }
    y += 11
  }

  /** Room a short table needs, for `sectionBand(..., keepWith)`. */
  const tableHeight = (rows: number) => 11 + (Math.min(rows, KEEP_TOGETHER_ROWS) + 1) * ROW_MM + 2

  const tableDefaults = {
    theme: 'grid' as const,
    headStyles: { fillColor: INK, textColor: 255 as any, fontStyle: 'bold' as const, fontSize: 7.5, cellPadding: 1.8 },
    styles: { fontSize: 7.5, cellPadding: 1.8, textColor: INK, lineColor: [225, 225, 225] as any, lineWidth: 0.1, overflow: 'linebreak' as const },
    alternateRowStyles: { fillColor: STRIPE as any },
    margin: { left: margin, right: margin, top: CONTINUE_TOP, bottom: FOOTER_RESERVE },
    tableWidth: contentWidth,
  }

  /**
   * A grid table. Column widths are fractions of the content width. A short
   * table (≤ KEEP_TOGETHER_ROWS) is never split: if it does not fit below the
   * current content it starts on the next page whole. Longer tables flow and
   * repeat their header on each page.
   */
  const table = (input: { head: string[]; body: string[][]; widths: number[]; align?: ('left' | 'right' | 'center')[]; boldFirst?: boolean }) => {
    const columnStyles: Record<number, any> = {}
    input.widths.forEach((fraction, index) => {
      columnStyles[index] = {
        cellWidth: contentWidth * fraction,
        halign: input.align?.[index] ?? 'left',
        ...(index === 0 && input.boldFirst ? { fontStyle: 'bold' } : {}),
      }
    })
    // A heading must never be stranded at the foot of a page without its first rows.
    ensureSpace(input.body.length <= KEEP_TOGETHER_ROWS ? (input.body.length + 1) * ROW_MM + 2 : 18)
    autoTable(doc, { ...tableDefaults, startY: y, head: [input.head], body: input.body, columnStyles })
    y = ((doc as any).lastAutoTable?.finalY ?? y) + 7
  }

  const emptyNote = (text: string) => {
    ensureSpace(10)
    doc.setFont('helvetica', 'italic')
    doc.setFontSize(8)
    doc.setTextColor(...MUTED)
    doc.text(text, margin + 1, y + 2, { maxWidth: contentWidth - 2 })
    y += 9
  }

  /** Plain explanatory paragraph (definitions, data notes). */
  const note = (text: string) => {
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(7.2)
    const lines = doc.splitTextToSize(text, contentWidth - 2)
    ensureSpace(lines.length * 3.4 + 3)
    doc.setTextColor(...MUTED)
    doc.text(lines, margin + 1, y + 2)
    y += lines.length * 3.4 + 3
  }

  /** KPI cards laid across the page width; more than five wrap onto another row. */
  const kpiRow = (cards: KpiCard[]) => {
    const perRow = Math.min(cards.length, 5)
    for (let start = 0; start < cards.length; start += perRow) {
      const row = cards.slice(start, start + perRow)
      const gap = 4
      const cardW = (contentWidth - gap * (perRow - 1)) / perRow
      const cardH = 22
      ensureSpace(cardH + 4)
      row.forEach((card, index) => {
        const x = margin + index * (cardW + gap)
        doc.setDrawColor(...BOX_BORDER)
        doc.setFillColor(...BOX_FILL)
        doc.roundedRect(x, y, cardW, cardH, 2, 2, 'FD')
        doc.setFont('helvetica', 'bold')
        doc.setFontSize(6.5)
        doc.setTextColor(...MUTED)
        doc.text(card.label.toUpperCase(), x + 3, y + 5.5, { maxWidth: cardW - 6 })
        doc.setFont('helvetica', 'bold')
        doc.setFontSize(card.value.length > 16 ? 11 : 13)
        doc.setTextColor(...INK)
        doc.text(card.value, x + 3, y + 13)
        doc.setFont('helvetica', 'normal')
        doc.setFontSize(6.8)
        if (card.delta === undefined || card.delta === null) doc.setTextColor(...MUTED)
        else doc.setTextColor(...(card.delta >= 0 ? POSITIVE : NEGATIVE))
        doc.text(doc.splitTextToSize(card.note, cardW - 6).slice(0, 2), x + 3, y + 17.5)
      })
      y += cardH + 6
    }
  }

  /** Orange bars with an optional ink line, drawn from the rows the web chart uses. */
  const barChart = (input: BarChartInput) => {
    const chartH = input.height ?? 44
    ensureSpace(chartH + 14)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(6.5)
    doc.setTextColor(...MUTED)
    doc.text(input.caption, margin, y + 1)
    y += 4
    const bars = input.bars
    const maxBar = Math.max(...bars.map((bar) => bar.value), 1)
    const barSlot = contentWidth / Math.max(bars.length, 1)
    const barW = Math.max(Math.min(barSlot * 0.55, 14), 1)
    const baseY = y + chartH

    doc.setDrawColor(...BOX_BORDER)
    doc.line(margin, baseY, margin + contentWidth, baseY)
    const labelEvery = Math.ceil(bars.length / 12)
    bars.forEach((bar, index) => {
      const cx = margin + index * barSlot + barSlot / 2
      const h = (bar.value / maxBar) * (chartH - 4)
      if (h > 0) {
        doc.setFillColor(...ORANGE)
        doc.rect(cx - barW / 2, baseY - h, barW, h, 'F')
      }
      if (index === 0 || index === bars.length - 1 || index % labelEvery === 0) {
        doc.setFont('helvetica', 'normal')
        doc.setFontSize(5.5)
        doc.setTextColor(...MUTED)
        doc.text(bar.label, cx, baseY + 3.5, { align: 'center' })
      }
    })

    if (input.line && input.line.length === bars.length && bars.length > 1) {
      const maxLine = Math.max(...input.line, 1)
      doc.setDrawColor(...INK)
      doc.setLineWidth(0.4)
      input.line.forEach((value, index) => {
        if (index === 0) return
        const x1 = margin + (index - 1) * barSlot + barSlot / 2
        const x2 = margin + index * barSlot + barSlot / 2
        const y1 = baseY - (input.line![index - 1] / maxLine) * (chartH - 4)
        const y2 = baseY - (value / maxLine) * (chartH - 4)
        doc.line(x1, y1, x2, y2)
      })
      doc.setLineWidth(0.2)
    }
    y = baseY + 9
  }

  /** Running header on pages after the first, footer with page numbers on all. Returns the file. */
  const finish = (filename: string, generatedAt: string): ReportPdfFile => {
    const totalPages = doc.getNumberOfPages()
    for (let page = 1; page <= totalPages; page++) {
      doc.setPage(page)
      if (page > 1) {
        doc.setFont('helvetica', 'bold')
        doc.setFontSize(9)
        doc.setTextColor(...INK)
        doc.text(options.title, margin, 12)
        doc.setTextColor(...ORANGE)
        doc.text(options.runningScope ?? options.scope, pageWidth - margin, 12, { align: 'right' })
        doc.setDrawColor(...BOX_BORDER)
        doc.line(margin, 15, pageWidth - margin, 15)
      }
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(7)
      doc.setTextColor(...MUTED)
      doc.text('Generated from Serapod2U', margin, pageHeight - 5)
      doc.text(`Generated: ${formatDateTimeMyt(generatedAt)} (MYT)`, pageWidth / 2, pageHeight - 5, { align: 'center' })
      doc.text(`Page ${page} of ${totalPages}`, pageWidth - margin, pageHeight - 5, { align: 'right' })
    }
    const blob = doc.output('blob')
    return { blob, filename, size: blob.size }
  }

  return {
    doc, margin, contentWidth, pageWidth, pageHeight,
    ensureSpace, newPage, infoGrid, sectionBand, tableHeight, table, emptyNote, note, kpiRow, barChart, finish,
    pageCount: () => doc.getNumberOfPages(),
  }
}
