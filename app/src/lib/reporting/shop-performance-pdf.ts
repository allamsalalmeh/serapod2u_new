/**
 * Serapod Shop Performance Report — branded A4 landscape PDF.
 *
 * Built only from the `ShopPerformanceReport` DTO the Shop Performance view
 * renders: no data access and no second calculation, only formatting. Visual
 * language: `report-pdf-kit.ts`, shared with the Product Performance report.
 * Personal contact details shown in the web drill-downs are deliberately not
 * exported.
 */

import { SHOP_RANKING_LIMIT, shopPerformanceFilename, type ShopPerformanceReport } from './shop-performance'
import {
  createReportPdf,
  formatCount,
  formatDateTimeMyt,
  formatDecimal,
  type ReportPdfFile,
} from './report-pdf-kit'

export const SHOP_PERFORMANCE_PDF_TITLE = 'SERAPOD SHOP PERFORMANCE REPORT'

export async function buildShopPerformancePdf(
  report: ShopPerformanceReport,
  options: { generatedAt?: string | null; generatedBy?: string | null; scopeLabel?: string } = {},
): Promise<ReportPdfFile> {
  const { period, kpis } = report
  const generatedAt = options.generatedAt ?? new Date().toISOString()
  const mtd = period.isCurrentMonth ? ' (month to date)' : ''
  const scopeLabel = options.scopeLabel ?? 'All shops'

  const pdf = await createReportPdf({
    title: SHOP_PERFORMANCE_PDF_TITLE,
    scope: `${period.label}${period.isCurrentMonth ? ' · Month to date' : ''}`,
    runningScope: `${period.label} · ${period.rangeLabel}`,
  })

  // ══ PAGE 1 — SUMMARY ═══════════════════════════════════════════════════
  pdf.infoGrid([
    ['REPORTING MONTH', period.label],
    ['REPORT PERIOD', period.rangeLabel + mtd],
    ['SHOP SCOPE', scopeLabel],
    ['GENERATED', formatDateTimeMyt(generatedAt)],
    ['GENERATED BY', options.generatedBy || '—'],
    ['REPORTING TIMEZONE', period.timeZone],
    ['DATA SOURCE', report.meta.source],
    ['REPORT DATE FIELD', report.meta.dateField],
  ])
  if (report.isEmpty) {
    pdf.emptyNote(`No shop scans were recorded in ${period.label} (${period.rangeLabel}). All figures below are zero.`)
  }

  pdf.sectionBand('MONTHLY SHOP ACTIVITY', period.rangeLabel + mtd)
  pdf.kpiRow([
    { label: 'Active Shops', value: formatCount(kpis.activeShops), note: 'shops with at least one scan in the period' },
    { label: 'Total Scans', value: formatCount(kpis.totalScans), note: 'consumer QR scans at shops in the period' },
    { label: 'Unique Consumers', value: formatCount(kpis.uniqueConsumers), note: 'identified consumers who scanned' },
    { label: 'Points Issued', value: formatCount(kpis.pointsIssued), note: 'points awarded on those scans' },
    { label: 'Avg Scans / Shop', value: formatDecimal(kpis.avgScansPerShop), note: 'total scans ÷ active shops' },
  ])

  pdf.sectionBand('DAILY SHOP ACTIVITY', period.rangeLabel + mtd, 72)
  if (report.dailyTrend.length === 0) {
    pdf.emptyNote('No days in the selected report period.')
  } else {
    const peakScans = Math.max(...report.dailyTrend.map((row) => row.scans), 0)
    const peakShops = Math.max(...report.dailyTrend.map((row) => row.shops), 0)
    pdf.barChart({
      bars: report.dailyTrend.map((row) => ({ label: row.label, value: row.scans })),
      line: report.dailyTrend.map((row) => row.shops),
      caption: `Bars: scans per day (peak ${formatCount(peakScans)})   ·   Line: shops active that day (peak ${formatCount(peakShops)})`,
    })
  }

  pdf.sectionBand('SHOP SIZE DISTRIBUTION', 'Active shops grouped by scans in the period', pdf.tableHeight(5))
  pdf.table({
    head: ['Scan Band', 'Shops', 'Share of Active Shops'],
    body: report.sizeDistribution.map((band) => [
      band.name,
      formatCount(band.count),
      band.sharePct === null ? '—' : `${band.sharePct.toFixed(1)}%`,
    ]),
    widths: [0.4, 0.3, 0.3],
    align: ['left', 'right', 'right'],
    boldFirst: true,
  })

  // ── Shop by Negeri & ranking ───────────────────────────────────────────
  pdf.sectionBand('SHOP BY NEGERI', 'Scans attributed through each shop\'s state', pdf.tableHeight(report.negeri.length || 1))
  if (report.negeri.length === 0) {
    pdf.emptyNote(report.isEmpty ? 'No shop scans in the selected report period.' : 'No scans could be attributed to a Negeri (shops have no state assigned).')
  } else {
    pdf.table({
      head: ['#', 'Negeri', 'Active Shops', 'Scans', 'Consumers', 'Points', 'Avg Scans / Shop'],
      body: report.negeri.map((row, index) => [
        String(index + 1),
        row.negeri,
        formatCount(row.shops),
        formatCount(row.scans),
        formatCount(row.consumers),
        formatCount(row.points),
        formatDecimal(row.avgPerShop),
      ]),
      widths: [0.05, 0.31, 0.13, 0.13, 0.13, 0.12, 0.13],
      align: ['center', 'left', 'right', 'right', 'right', 'right', 'right'],
    })
    if (report.unassignedNegeriScans > 0) {
      pdf.note(`${formatCount(report.unassignedNegeriScans)} scan(s) belong to shops with no state assigned and are not shown in the Negeri table; they are included in every other total.`)
    }
  }

  const ranking = report.shopRanking.slice(0, SHOP_RANKING_LIMIT)
  pdf.sectionBand(
    'SHOP PERFORMANCE RANKING',
    report.shopRanking.length > ranking.length
      ? `Top ${ranking.length} of ${formatCount(report.shopRanking.length)} active shops by scans`
      : `${formatCount(report.shopRanking.length)} active shops by scans`,
  )
  if (ranking.length === 0) {
    pdf.emptyNote('No shops recorded scans in the selected report period.')
  } else {
    pdf.table({
      head: ['#', 'Shop', 'Scans', 'Share of Scans', 'Consumers', 'Points', 'Last Scan'],
      body: ranking.map((row) => [
        String(row.rank),
        row.name,
        formatCount(row.scans),
        row.scanSharePct === null ? '—' : `${row.scanSharePct.toFixed(1)}%`,
        formatCount(row.consumers),
        formatCount(row.points),
        formatDateTimeMyt(row.lastScanAt),
      ]),
      widths: [0.05, 0.37, 0.1, 0.12, 0.11, 0.1, 0.15],
      align: ['center', 'left', 'right', 'right', 'right', 'right', 'left'],
    })
  }

  pdf.sectionBand('METRIC DEFINITIONS', undefined, 34)
  pdf.note([
    'Every figure counts genuine consumer QR scans attributed to a shop (manual point adjustments excluded) whose scan time falls inside the report period in Malaysia time.',
    'A historical month covers the complete calendar month; the current month covers the 1st to today. No lifetime totals are included.',
    'Active Shops are shops with at least one scan in the period; Unique Consumers count identified consumers once each, however many shops they scanned at.',
  ].join(' '))

  return pdf.finish(shopPerformanceFilename(period), generatedAt)
}
