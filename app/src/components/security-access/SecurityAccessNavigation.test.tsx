// @vitest-environment jsdom
import { describe, it, expect, vi, beforeEach } from 'vitest'
import { cleanup, render, screen, fireEvent, waitFor } from '@testing-library/react'

vi.mock('./PeopleAccessPanel', () => ({ default: () => <div>people-panel</div> }))
vi.mock('./RolesPoliciesPanel', () => ({ default: ({ initialQuery }: any) => <div>roles-panel:{initialQuery}</div> }))
vi.mock('./GovernancePanel', () => ({ default: ({ section }: any) => <div>governance-panel:{section}</div> }))
vi.mock('./TechnicalAccessPanel', () => ({ default: () => <div>technical-panel</div>, LegacyCompatibilityPanel: () => null }))
vi.mock('./AccessSimulator', () => ({ default: () => <div>simulator-panel</div> }))
vi.mock('./AccessChangeLog', () => ({ default: () => <div>changes-panel</div>, ParityEvidence: () => <div>parity-panel</div> }))
vi.mock('./DecisionLog', () => ({ default: ({ initialFilter }: any) => <div>decisions-panel:{initialFilter}</div> }))
vi.mock('./client-api', () => ({ callApi: vi.fn().mockResolvedValue({ ok: false, error: 'x' }) }))
import SecurityAccessView from './SecurityAccessView'

const base = { schemaReady: true, people: [], actors: [], roles: [], organizations: [], permissions: [], decisions: [], recentDecisions: [] }
beforeEach(() => {
  cleanup()
  window.history.replaceState(null, '', '/security-access')
  // Overview succeeds; the governance read model is denied (sections stay informational).
  global.fetch = vi.fn().mockImplementation(async (url: string) => String(url).includes('/governance')
    ? { ok: false, status: 403, headers: new Headers(), json: async () => ({ error: 'Forbidden' }) }
    : { ok: true, status: 200, headers: new Headers(), json: async () => base }) as any
})

describe('Security & Access navigation', () => {
  it('shows four main tabs with the secondary sections under Advanced', async () => {
    render(<SecurityAccessView userProfile={{}} />)
    await screen.findByRole('tab', { name: 'Advanced' })
    expect(screen.getAllByRole('tab').map(t => t.textContent)).toEqual(['Overview', 'People & Access', 'Roles & Policies', 'Advanced'])
    fireEvent.click(screen.getByRole('tab', { name: 'Advanced' }))
    expect(window.location.search).toBe('?tab=advanced&section=governance')
    // One dropdown replaces the stacked Advanced tab bars; closed by default.
    expect(screen.queryByRole('listbox')).toBeNull()
    expect(screen.getAllByRole('tab')).toHaveLength(4)
    expect(screen.getByRole('button', { name: /Advanced destination: Governance \/ Access Requests/ })).toBeTruthy()
    const pick = async (name: string) => {
      fireEvent.click(screen.getByRole('button', { name: /^Advanced destination/ }))
      fireEvent.click(await screen.findByRole('option', { name }))
    }
    await pick('Data Scope')
    expect(await screen.findByText('No scopes defined.')).toBeTruthy()
    expect(window.location.search).toBe('?tab=advanced&section=scopes')
    await pick('Approval Limits')
    expect(await screen.findByText('Approval Limits need the Security audit view.')).toBeTruthy()
    expect(window.location.search).toBe('?tab=advanced&section=authority')
    await pick('Technical Access')
    expect(screen.getByText('technical-panel')).toBeTruthy()
    await pick('Governance / Delegations')
    expect(screen.getByText('governance-panel:delegations')).toBeTruthy()
    expect(window.location.search).toBe('?tab=advanced&section=governance&gov=delegations')
    await pick('Audit & Diagnostics / Parity evidence')
    expect(screen.getByText('parity-panel')).toBeTruthy()
    expect(window.location.search).toBe('?tab=advanced&section=audit&audit=parity')
    fireEvent.click(screen.getByRole('tab', { name: 'Overview' }))
    fireEvent.click(screen.getByRole('tab', { name: 'Advanced' }))
    expect(screen.getByText('parity-panel')).toBeTruthy()
  })
  it('groups destinations under non-selectable headings and supports keyboard + Escape', async () => {
    window.history.replaceState(null, '', '/security-access?tab=advanced')
    render(<SecurityAccessView userProfile={{}} />)
    const trigger = await screen.findByRole('button', { name: /^Advanced destination/ })
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    const options = screen.getAllByRole('option')
    expect(options.map(o => o.textContent)).toEqual(['Access Requests', 'Delegations', 'Access Reviews', 'Segregation of Duties', 'Emergency Access', 'Technical Access', 'Data Scope', 'Approval Limits', 'Authorization decisions', 'Access changes', 'Parity evidence', 'Access simulator'])
    expect(screen.getByText('Governance').getAttribute('role')).toBe('presentation')
    expect(screen.getByText('Audit & Diagnostics').getAttribute('role')).toBe('presentation')
    expect(document.activeElement).toBe(options[0])
    fireEvent.keyDown(options[0], { key: 'ArrowDown' })
    expect(document.activeElement).toBe(options[1])
    fireEvent.keyDown(options[1], { key: 'End' })
    expect(document.activeElement).toBe(options[11])
    fireEvent.keyDown(options[11], { key: 'Escape' })
    expect(screen.queryByRole('listbox')).toBeNull()
    expect(document.activeElement).toBe(trigger)
    fireEvent.keyDown(trigger, { key: 'ArrowDown' })
    fireEvent.keyDown(screen.getAllByRole('option')[7], { key: 'Enter' })
    expect(await screen.findByText('Approval Limits need the Security audit view.')).toBeTruthy()
    expect(window.location.search).toBe('?tab=advanced&section=authority')
  })
  it('opens governance sub-destination deep links and survives Back/Forward', async () => {
    window.history.replaceState(null, '', '/security-access?tab=advanced&section=governance&gov=sod')
    render(<SecurityAccessView userProfile={{}} />)
    await screen.findByText('governance-panel:sod')
    fireEvent.click(screen.getByRole('button', { name: /^Advanced destination/ }))
    fireEvent.click(await screen.findByRole('option', { name: 'Audit & Diagnostics / Access changes' }))
    expect(screen.getByText('changes-panel')).toBeTruthy()
    window.history.back()
    await screen.findByText('governance-panel:sod')
    window.history.forward()
    await screen.findByText('changes-panel')
  })
  it('opens old Data Scope / Authority Policies links on the matching Advanced sections', async () => {
    window.history.replaceState(null, '', '/security-access?tab=scopes')
    const { unmount } = render(<SecurityAccessView userProfile={{}} />)
    await screen.findByText('No scopes defined.')
    unmount()
    window.history.replaceState(null, '', '/security-access?tab=authority')
    render(<SecurityAccessView userProfile={{}} />)
    await screen.findByText('Approval Limits need the Security audit view.')
    unmount()
    // Old Roles & Policies deep links into the moved panels land on Advanced too.
    window.history.replaceState(null, '', '/security-access?tab=roles&section=authority')
    render(<SecurityAccessView userProfile={{}} />)
    await screen.findByText('Approval Limits need the Security audit view.')
  })
  it('opens legacy and deep links to the right Advanced section with context', async () => {
    window.history.replaceState(null, '', '/security-access?tab=audit')
    const { unmount } = render(<SecurityAccessView userProfile={{}} />)
    await screen.findByText('decisions-panel:all')
    unmount()
    window.history.replaceState(null, '', '/security-access?tab=advanced&section=audit&diff=1')
    render(<SecurityAccessView userProfile={{}} />)
    await screen.findByText('decisions-panel:differences')
  })
  it('restores the section on browser Back', async () => {
    render(<SecurityAccessView userProfile={{}} />)
    fireEvent.click(await screen.findByRole('tab', { name: 'People & Access' }))
    expect(screen.getByText('people-panel')).toBeTruthy()
    window.history.back()
    await waitFor(() => expect(screen.queryByText('people-panel')).toBeNull())
  })
  it('moves between main tabs with arrow keys', async () => {
    render(<SecurityAccessView userProfile={{}} />)
    const overview = await screen.findByRole('tab', { name: 'Overview' })
    overview.focus()
    fireEvent.keyDown(overview, { key: 'ArrowRight' })
    expect(screen.getByRole('tab', { name: 'People & Access' }).getAttribute('aria-selected')).toBe('true')
  })
})
